"use client";

import { useEffect, useState } from "react";

/**
 * Смонтирован ли компонент на клиенте.
 *
 * Нужен там, где значение зависит от текущего времени. Страница отдаётся
 * статикой: даты в ней посчитаны в момент сборки, а на клиенте пересчитаются
 * заново — разметка разойдётся, и React переберёт дерево заново, ругнувшись
 * ошибкой гидратации. Пока не смонтировались, такие места оставляем пустыми:
 * пропущенная на один кадр подпись дешевле пересборки экрана.
 */
export function useMounted(): boolean {
  const [mounted, setMounted] = useState(false);
  useEffect(() => setMounted(true), []);
  return mounted;
}
