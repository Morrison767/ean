/**
 * Находка риск-правила.
 *
 * Один вид на все разборы: по занятости, по хозяйственной деятельности и по
 * тому, что появится дальше. Форма одна не ради экономии кода, а ради чтения:
 * аналитик привыкает, что находка это всегда «что нашли — на каких фактах —
 * куда пойти сверять», и не разбирает каждый блок заново.
 *
 * Поле evidence обязательное и непустое по смыслу: утверждение без фактов —
 * мнение, а решение по субъекту принимает человек, а не система.
 */

export interface RiskFinding {
  id: string;
  title: string;
  severity: "high" | "medium";
  /** Проверяемые факты, из которых складывается находка. */
  evidence: string[];
  /** Куда пойти сверять. */
  link?: { label: string; href: string };
  /** Ключи записей, которых находка касается: их подсвечивают в списке. */
  records?: string[];
}

/** Тяжёлые сверху; внутри одного веса порядок появления — он тематический. */
export const bySeverity = (a: RiskFinding, b: RiskFinding): number =>
  a.severity === b.severity ? 0 : a.severity === "high" ? -1 : 1;
